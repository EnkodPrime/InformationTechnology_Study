    /** Схема срещу състояние: „Name е уникално днес“ не доказва ключ. */
    schema_vs_state({ rows }) {
      const names = String(rows).split(/[,;]+/).map((x) => x.trim()).filter(Boolean);
      if (!names.length) throw new Error("Въведи поне едно име.");
      if (names.length > 10) throw new Error("Най-много 10 имена.");
      names.forEach((n) => { if (n.length > 15) throw new Error(`„${n}“ е по-дълго от 15 знака.`); });
      const F = [], seen = new Map();
      let firstDup = -1;
      F.push({ rows: [], msg: "Схема: Student(id, name). Ограничение: id е първичен ключ. Name няма ограничение за уникалност." });
      names.forEach((n, i) => {
        const dup = seen.has(n);
        const cur = names.slice(0, i + 1).map((x, k) => ({ id: k + 1, name: x }));
        if (dup && firstDup < 0) firstDup = i;
        F.push({ rows: cur, hl: dup ? [seen.get(n), i] : [i], dup,
          msg: dup ? `Ред ${i + 1}: (${i + 1}, ${n}) — същото име като ред ${seen.get(n) + 1}. <b>Допустимо</b>: схемата не забранява еднакви имена.` : `Ред ${i + 1}: (${i + 1}, ${n}). Всички имена засега са различни.`,
          inv: dup ? { text: "name не е уникално ⇒ не може да е ключ", ok: false } : { text: "в ТОВА състояние name е уникално — но това не е доказателство", ok: true },
          log: `+ (${i + 1}, ${n})` });
        if (!dup) seen.set(n, i);
      });
      F.push({ rows: names.map((x, k) => ({ id: k + 1, name: x })), done: true, msg: firstDup < 0 ? "В текущото <dfn data-g=\"състояние на база\">състояние</dfn> имената са различни. Въпреки това name <b>не е ключ</b>: ключът трябва да е уникален във <i>всяко допустимо</i> състояние, а правилото на предметната област допуска двама студенти с едно име." : "Състоянието показа контрапример. Но и без него name не е ключ — решава правилото, не данните." });
      return { frames: F, firstDup };
    },
