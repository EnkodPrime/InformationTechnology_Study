/* Раздел 4 — Управление на проекти и PMIS (ръководство, глава 3, част „Управление на проекти и PMIS“; схема 6). */
(function () {
  const S = window.Study, h = S.h, DG = window.DG;

  /* ---------- чисти функции ---------- */
  const algos = {
    /** Сценарият от ръководството: задача T17 „Импорт на студентите“, отговорник Ана, срок 20 октомври.
        same_day — процедурата изисква блокиращ проблем да се отчита в същия ден;
        role_ok  — ролята на ръководителя има право да одобри промяна на срок. */
    pmis_flow({ report_day, same_day, role_ok }) {
      const d = S.int(report_day, 15, 25, "Денят на отчета");
      const F = [];
      const add = (n, kind, msg, log, extra) => F.push(Object.assign({ n, kind, msg, log, day: d }, extra || {}));
      add("work", "tps", "Задача <b>T17</b> „Импорт на студентите“, отговорник Ана, срок <b>20 октомври</b>. Импортът е блокиран от липсващ файл.", "T17: блокирана");
      const late = same_day && d > 18;
      if (late) add("work", "proc", `Процедурата изисква блокиращ проблем да се отчита <b>в същия ден</b> (18 окт.). Ана отчита на ${d} окт. — <b>нарушение на процедурата</b>; информацията закъснява с ${d - 18} дни.`, "процедура ✗", { bad: true });
      add("input", "tps", `<b>Вход (${d} окт.):</b> Ана записва, че импортът е блокиран от липсващ файл. Записването на отчет е <b>оперативна</b> (TPS) функция на PMIS.`, `отчет ${d} окт.`);
      add("store", "tps", "PMIS <b>съхранява</b> отчета и го <b>свързва</b> със зависимите задачи (напр. проверка на записванията, обучение).", "съхранение + връзки");
      add("report", "mis", `PMIS представя <b>справка за блокираната работа</b>. Седмичната справка за сроковете е <b>управленска</b> (MIS) функция на същата PMIS. ${d > 20 ? "<b>Срокът вече е изтекъл.</b>" : `До срока остават ${20 - d} дни.`}`, "справка (MIS)", { warn: d > 20 });
      add("decide", "human", "<b>Ръководителят решава</b> кой да осигури файла и дали да промени плана. Системата подпомага решението; самото наличие на справка не определя правилното действие.", "решение — човек");
      if (role_ok) add("change", "feedback", "Ролята на ръководителя има право да одобри промяна на срок → срокът на T17 се променя. <b>Обратна връзка</b> = промяна в работата, не просто показване на данни.", "срокът е променен", { ok: true });
      else add("change", "feedback", "Правата позволяват само на друга роля да одобрява промяна на срок → ръководителят <b>не може</b> да го промени сам; решението ескалира. Една и съща програма с различни правила и роли участва в различно организирани системи.", "няма право → ескалация", { bad: true });
      return { frames: F, late, changed: !!role_ok };
    },
  };

  const html = `
<div class="prose">
  <p><b>Системите за управление на проекти информационни системи ли са?</b> Да. Когато говорим за софтуер, който съхранява задачи, срокове, отговорници и отчети за проекти, разглеждаме информационна система според обслужваната дейност. <dfn data-g="pmis">PMIS</dfn> (Project Management Information System) събира, свързва и предоставя информация за проектната работа. Конкретната организационна система включва също хората, правилата за отчитане и правата за вземане на решения. [M07 R03]</p>
  <p>Самото <dfn data-g="project management">project management</dfn> е управленска дейност; софтуерът я подпомага. В по-широкия смисъл „система за управление на проекти“ е цялостната организация на управлението — отговорности, планиране, контрол и информационна подкрепа — и PMIS е нейна информационна подсистема. [M07 R04]</p>
</div>

<div class="block">
  <h3>Четири различни неща с подобни имена</h3>
  <p class="muted">Щракни слой. При двусмислие уточняваме дали говорим за приложение, информационна система или организационен начин на управление.</p>
  <div id="layers"></div>
  <div class="detail" id="layers-det"></div>
</div>

<div class="block">
  <h3>Схема 6. PMIS свързва отчетената работа с управленските решения</h3>
  <p class="prose">Учебният проект: внедряване на университетски портал. Промени деня на отчета, процедурата и правата — виж как едни и същи данни в различно организирана система водят до различен резултат.</p>
  <div id="v-pmis"></div>
  <details class="hint"><summary>Хинт: защо това е информационна система</summary><div>
    <p>Тук присъстват всички характерни елементи: <b>участници</b> (Ана, ръководителят), <b>данни</b> (задача, срок, отчет), <b>процедури</b> (отчет в същия ден), <b>обработка</b> (свързване със зависимите задачи), <b>изходна информация</b> (справка) и <b>обратна връзка</b> (промяна на плана).</p>
  </div></details>
</div>

<div class="block">
  <h3>Припокриване на класификациите</h3>
  <p class="prose">PMIS класифицира системата според <b>предназначението</b> ѝ. <dfn data-g="tps">TPS</dfn> описва оперативна обработка на събития, а <dfn data-g="mis">MIS</dfn> в използваната тук по-тясна класификация описва управленски справки и обобщения. Записването на изпълнена задача може да е оперативна функция, а седмичната справка за сроковете — управленска функция на <b>същата</b> PMIS. Следователно тези етикети не са непременно взаимно изключващи се.</p>
  <p class="prose"><dfn data-g="jira">Jira</dfn> е реален пример за инструмент за планиране и проследяване на работа: задачи с отговорници, начални и крайни дати, работни потоци и изгледи за състоянието. В организацията може да е софтуерен компонент на PMIS. Една инсталация не осигурява автоматично всички функции на управлението на проекти. [M07 R05]</p>
  <details class="trap"><summary>Капан: „управленска информационна система“</summary><div><p>Изразът се използва и по-широко от тесния клас MIS. Винаги проверявай значението в конкретния учебен контекст.</p></div></details>
</div>

<div class="block">
  <h3>Проект за създаване на система ≠ система за управление на проекта</h3>
  <div class="tbl-wrap"><table class="t">
    <tr><th></th><th>Университетски портал</th><th>PMIS на екипа</th></tr>
    <tr><th>Роля</th><td>Резултатът, който екипът разработва</td><td>Средството, с което екипът организира и отчита разработването</td></tr>
    <tr><th>Данни</th><td>Студенти, дисциплини, записвания</td><td>Задачи, отговорници, срокове, проблеми</td></tr>
    <tr><th>Обслужва</th><td>Учебния процес</td><td>Проектната работа</td></tr>
    <tr><th>Край</th><td>Жизненият цикъл продължава: експлоатация, поддръжка, промени</td><td>Проектът по първоначалното внедряване може да приключи</td></tr>
  </table></div>
  <p class="prose"><b>Проектирането</b> определя как системата ще работи — роли, модели на данните, интерфейси и проверки. <b>Управлението на проекта</b> организира кой ще извърши работата, кога, с какви ресурси и как ще се следят отклоненията. Дейностите са свързани, но не са синоними.</p>
  <details class="trap"><summary>Капан: Scrum и Kanban като продукти</summary><div>
    <p><dfn data-g="scrum">Scrum</dfn> е рамка за работа, а <dfn data-g="kanban">Kanban</dfn> се използва за организиране и управление на потока на работа. Не са имена на софтуерни продукти. „Kanban дъска“ може да бъде изглед в приложение — това не прави дъската равнозначна на цялата информационна система или на цялостното управление на проект.</p>
  </div></details>
</div>`;

  const LAYERS = [
    { k: "pm", t: "Управление на проекти", s: "дейност", d: "Управленска дейност: планиране, контрол, отговорности. Не е име на програма." },
    { k: "org", t: "Система за упр. на проекти (широк смисъл)", s: "организация", d: "Цялостната организация на управлението — отговорности, планиране, контрол и информационна подкрепа. [M07 R04]" },
    { k: "pmis", t: "PMIS", s: "информационна система", d: "Информационна подсистема: хора, правила за отчитане, права, данни за задачи и срокове + софтуер. [M07 R03]" },
    { k: "sw", t: "Jira (или друг продукт)", s: "софтуерен компонент", d: "Конкретен продукт за планиране и проследяване на работа. Внедряването определя кои процедури, интеграции и отчети са налични. [M07 R05]" },
  ];

  function mount(root) {
    const host = root.querySelector("#layers"), det = root.querySelector("#layers-det");
    let sel = "pmis";
    function drawL() {
      host.innerHTML = "";
      const svg = DG.root(640, 270);
      const BOX = [[20, 15, 600, 245], [50, 55, 540, 195], [80, 95, 480, 145], [110, 150, 240, 75]];
      LAYERS.forEach((L, i) => {
        const [x, y, w, hh] = BOX[i];
        const g = S.svg("g", { class: "nd click " + (L.k === sel ? "s-act sel" : i === 3 ? "s-piv" : ""), tabindex: 0, role: "button", "aria-label": L.t });
        g.append(S.svg("rect", { x, y, width: w, height: hh, rx: 10, style: "fill-opacity:.6" }));
        g.append(S.svg("text", { x: x + 12, y: y + 22, class: "ttl", text: L.t.replace(" (или друг продукт)", "") }));
        g.append(S.svg("text", { x: i === 3 ? x + 12 : x + w - 12, y: i === 3 ? y + 44 : y + 22, "text-anchor": i === 3 ? "start" : "end", class: "sub", text: L.s }));
        const go = () => { sel = L.k; drawL(); };
        g.addEventListener("click", go); g.addEventListener("keydown", (e) => { if (e.key === "Enter") go(); });
        svg.append(g);
      });
      DG.text(svg, 455, 180, "хора, правила за отчитане,", "sub");
      DG.text(svg, 455, 196, "права, данни за задачи", "sub");
      DG.wrap(host, svg);
      const L = LAYERS.find((x) => x.k === sel);
      det.innerHTML = `<h4>${L.t} <span class="pill">${L.s}</span></h4><p>${L.d}</p>`;
    }
    drawL();

    const NODES = {
      work: { x: 90, y: 60, t: "Работа по T17\n(Ана)" },
      input: { x: 270, y: 60, t: "Отчет\n(вход)" },
      store: { x: 450, y: 60, t: "PMIS: запис\n+ връзки" },
      report: { x: 450, y: 190, t: "Справка за\nблокираната работа" },
      decide: { x: 270, y: 190, t: "Ръководител\n(решение)" },
      change: { x: 90, y: 190, t: "Промяна\nна плана" },
    };
    const ORDER = ["work", "input", "store", "report", "decide", "change"];
    const KIND = { tps: "TPS функция", mis: "MIS функция", human: "човешко решение", feedback: "обратна връзка", proc: "процедура" };
    S.viz(root.querySelector("#v-pmis"), {
      id: "pmis", title: "Отчет → справка → решение → промяна", sub: "Собствен учебен модел от ръководството.", code: false,
      inputs: [
        { id: "report_day", label: "ден на отчета (окт.)", type: "number", value: 18, width: "6em" },
        { id: "same_day", label: "процедура: отчет в същия ден", type: "checkbox", value: true },
        { id: "role_ok", label: "ръководителят има право да промени срок", type: "checkbox", value: true },
      ],
      presets: [{ label: "Късен отчет", values: { report_day: 22 } }, { label: "Без права", values: { role_ok: false, report_day: 18 } }],
      build: algos.pmis_flow,
      legend: [["s-act", "текуща стъпка"], ["s-done", "минала"], ["s-swap", "проблем"]],
      draw(st, f, { frames, i }) {
        st.innerHTML = "";
        const svg = DG.root(560, 250);
        const seen = new Set(frames.slice(0, i + 1).map((x) => x.n));
        ORDER.forEach((k, j) => {
          if (j === ORDER.length - 1) return;
          const A = NODES[k], B = NODES[ORDER[j + 1]];
          const pts = A.y === B.y ? [[A.x + (B.x > A.x ? 70 : -70), A.y], [B.x + (B.x > A.x ? -70 : 70), B.y]] : [[A.x, A.y + 26], [B.x, B.y - 28]];
          DG.line(svg, pts, { cls: f.n === ORDER[j + 1] ? "s-act" : seen.has(ORDER[j + 1]) ? "s-done" : "" });
        });
        DG.line(svg, [[90, 162], [90, 88]], { cls: f.n === "change" ? (f.bad ? "s-swap" : "s-done") : "", dash: true, label: "обратна връзка", lx: 100, ly: 128, anchor: "start" });
        ORDER.forEach((k) => {
          const N = NODES[k];
          DG.node(svg, { x: N.x, y: N.y, w: 140, h: 50, t: N.t, cls: f.n === k ? (f.bad ? "s-swap" : "s-act") : seen.has(k) ? "s-done" : "" });
        });
        DG.wrap(st, svg);
        st.append(h("p", { class: "mini", html: `Вид на стъпката: <span class="pill ${f.bad ? "s-swap" : "s-piv"}">${KIND[f.kind]}</span>` }));
      },
    });
  }

  S.chapter({ id: "pmis", order: 4, num: "4", group: "Класификация", title: "Управление на проекти и PMIS", lead: "PMIS е информационна система; управлението на проекти е дейност; Jira е софтуерен компонент. Проект за система ≠ система за проекта.", html, mount, algos });
})();
