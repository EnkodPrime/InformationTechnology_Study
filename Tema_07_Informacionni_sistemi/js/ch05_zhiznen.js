/* Раздел 5 — Жизнен цикъл (ръководство, глава 4; схема 7). */
(function () {
  const S = window.Study, h = S.h, DG = window.DG;

  const PH = [
    { k: "need", t: "Потребност", d: "Възниква проблем или възможност. „Нужна ни е система“ не казва дали се цели по-малко грешки, по-кратко обработване или проследимост.", out: "формулиран проблем и цел" },
    { k: "feas", t: "Осъществимост", d: "Оценява технически, икономически и организационни условия.", out: "решение дали да се продължи", g: "осъществимост" },
    { k: "anal", t: "Анализ на изискванията", d: "Установява проблема, участниците и критериите за успех.", out: "проверими изисквания и приемателни критерии" },
    { k: "des", t: "Проектиране", d: "Определя структурата на решението.", out: "архитектура, модел на данните, интерфейси" },
    { k: "impl", t: "Реализация", d: "Създава компонентите.", out: "компоненти" },
    { k: "ver", t: "Проверка", d: "Сравнява действителното поведение с изискванията и нуждите.", out: "свидетелства за съответствие и пригодност" },
    { k: "dep", t: "Внедряване", d: "Повече от инсталация: прехвърляне на данни, обучение, промяна на процедури и план за преминаване.", out: "система в реална организационна употреба", g: "внедряване" },
    { k: "ops", t: "Експлоатация", d: "Следи работата. Поражда нови потребности.", out: "измервания, инциденти, нови потребности" },
    { k: "mnt", t: "Поддръжка", d: "Поправяне на дефекти, адаптация към средата и промяна на възможностите.", out: "нови версии" },
    { k: "ret", t: "Извеждане от употреба", d: "Решения за архивиране, прехвърляне или унищожаване на данни според приложимите изисквания; отношение към архиви, интеграции и достъп.", out: "архив, прекратени интерфейси" },
  ];

  /* ---------- чисти функции ---------- */
  const algos = {
    /** Обход на жизнения цикъл с обратна връзка: експлоатацията поражда нова потребност (cycles пъти).
        Пропуснатите дейности (skip) се отчитат като риск, който проличава по-късно. */
    lifecycle({ cycles, skip_owner, skip_train, ext_api }) {
      const c = S.int(cycles, 0, 3, "Броят нови потребности");
      const F = [];
      let gen = 1, risks = 0;
      const pass = (from) => {
        for (let i = from; i < PH.length - 1; i++) {
          const P = PH[i];
          let msg = `<b>${P.t}</b> (версия ${gen}). ${P.d} <span class="muted">Резултат: ${P.out}.</span>`, bad = false;
          if (P.k === "dep" && skip_train) { msg += " <b>Пропуснато обучение и промяна на процедурите</b> — инсталирано е, но не е внедрено."; bad = true; risks++; }
          if (P.k === "ops" && skip_owner) { msg += " <b>Няма отговорник за данните</b> — технически внедрена, организационно неработоспособна."; bad = true; risks++; }
          F.push({ i, gen, bad, msg, log: `${P.t}${bad ? " ✗" : ""}`, stats: { версия: gen, рискове: risks } });
        }
      };
      pass(0);
      for (let k = 0; k < c; k++) {
        F.push({ i: 7, gen, fb: true, msg: `<b>Обратна връзка:</b> експлоатацията поражда нова потребност (напр. нов учебен план). Цикълът се връща към анализа — не започва от нулата.`, log: "↺ нова потребност", stats: { версия: gen, рискове: risks } });
        gen++;
        pass(2);
      }
      const P = PH[PH.length - 1];
      let msg = `<b>${P.t}.</b> ${P.d}`, bad = false;
      if (ext_api) { msg += " <b>Старият интерфейс е спрян, но външна интеграция още работи</b> — реален процес прекъсва, въпреки че новата система сама по себе си е функционална."; bad = true; risks++; }
      F.push({ i: PH.length - 1, gen, bad, msg, log: `${P.t}${bad ? " ✗" : ""}`, stats: { версия: gen, рискове: risks } });
      return { frames: F, versions: gen, risks };
    },
  };

  const html = `
<div class="prose">
  <p><dfn data-g="жизнен цикъл">Жизненият цикъл</dfn> обхваща възникване на потребност, изследване на <dfn data-g="осъществимост">осъществимостта</dfn>, анализ на изискванията, проектиране, реализация, проверка, <dfn data-g="внедряване">внедряване</dfn>, експлоатация, поддръжка и извеждане от употреба. Това са <b>логически дейности</b>; различните процесни модели ги подреждат и повтарят по различен начин (раздел <a href="#modeli">8</a>). Английското означение е <dfn data-g="sdlc">SDLC</dfn>.</p>
</div>

<div class="block">
  <h3>Схема 7. Жизненият цикъл има обратна връзка</h3>
  <p class="muted">Щракни дейност. Експлоатацията поражда нови потребности — затова е цикъл, а не права линия.</p>
  <div id="s7"></div>
  <div class="detail" id="s7-det"></div>
</div>

<div class="block">
  <h3>Симулация: няколко версии и пропуснати дейности</h3>
  <p class="prose">Разходите и рисковете продължават след първото пускане. Включи пропуск и пусни: пропуснатата дейност не спира разработката, но проличава по-късно.</p>
  <div id="v-lc"></div>
  <div class="key">Резултатите на всяка дейност трябва да имат <b>проверими критерии за приемане</b>. Жизненият цикъл е цикъл на организационна система, а не само на програмен код.</div>
</div>

<div class="block">
  <h3>Жизнен цикъл ≠ модел на разработване</h3>
  <div class="split">
    <div class="card"><h4>Жизнен цикъл</h4><p>Целият живот: възникване на потребност, създаване, използване, промени и извеждане от употреба.</p></div>
    <div class="card"><h4>Модел на разработване</h4><p>Организира дейностите <b>вътре</b> в този живот: последователно, итеративно или чрез други подходи.</p></div>
  </div>
  <details class="trap"><summary>Капан: инсталация = внедряване</summary><div>
    <p>Разработването не приключва с първия работещ екран, а внедряването не е само копиране на файлове на сървър. Внедряването включва прехвърляне на данни, обучение, промяна на процедури и план за преминаване.</p>
  </div></details>
  <details class="hint"><summary>Хинт: целта определя критерия за успех</summary><div>
    <p>Преди реализацията трябва да има разбираем проблем и критерий за резултат. Ако целта е намаляване на двойните записвания, броят екрани не измерва успеха. Приемателният критерий трябва да е свързан с поведението при едновременни заявления и с правилото за идентичност на записването (виж раздел <a href="#proektirane">7</a>).</p>
  </div></details>
</div>`;

  function mount(root) {
    const host = root.querySelector("#s7"), det = root.querySelector("#s7-det");
    let sel = 0;
    function pos(i, n) { const a = -Math.PI / 2 + (i * 2 * Math.PI) / n; return [320 + 245 * Math.cos(a), 180 + 140 * Math.sin(a)]; }
    function draw7() {
      host.innerHTML = "";
      const svg = DG.root(640, 360);
      const n = PH.length;
      for (let i = 0; i < n - 1; i++) {
        const [x1, y1] = pos(i, n), [x2, y2] = pos(i + 1, n);
        const dx = x2 - x1, dy = y2 - y1, L = Math.hypot(dx, dy), ux = dx / L, uy = dy / L;
        DG.line(svg, [[x1 + ux * 52, y1 + uy * 22], [x2 - ux * 52, y2 - uy * 22]]);
      }
      const [ox, oy] = pos(7, n), [ax, ay] = pos(2, n);
      DG.line(svg, [[ox + 20, oy - 20], [320, 180], [ax - 20, ay + 20]], { cls: "s-piv", dash: true });
      DG.text(svg, 320, 172, "нова потребност", "el");
      PH.forEach((P, i) => {
        const [x, y] = pos(i, n);
        DG.node(svg, { x, y, w: 112, h: 40, t: P.t.replace("Анализ на изискванията", "Анализ").replace("Извеждане от употреба", "Извеждане"), key: P.k, cls: i === sel ? "s-act" : i >= 7 ? "s-piv" : "", onclick: () => { sel = i; draw7(); } });
      });
      DG.select(svg, PH[sel].k);
      DG.wrap(host, svg);
      const P = PH[sel];
      det.innerHTML = `<h4>${P.g ? `<dfn data-g="${P.g}" tabindex="0">${P.t}</dfn>` : P.t}</h4><p>${P.d}</p><p class="mini">Резултат за приемане: ${P.out}.</p>`;
    }
    draw7();

    S.viz(root.querySelector("#v-lc"), {
      id: "lc", title: "Жизнен цикъл през няколко версии", sub: "Последователността е логическа; при нова потребност цикълът се връща към анализа.", code: false,
      inputs: [
        { id: "cycles", label: "нови потребности", type: "number", value: 1, width: "5em" },
        { id: "skip_train", label: "пропусни обучение", type: "checkbox", value: false },
        { id: "skip_owner", label: "няма отговорник за данните", type: "checkbox", value: false },
        { id: "ext_api", label: "външна интеграция при извеждане", type: "checkbox", value: false },
      ],
      presets: [{ label: "Всички пропуски", values: { skip_train: true, skip_owner: true, ext_api: true } }, { label: "Без обратна връзка", values: { cycles: 0 } }],
      legend: [["s-act", "текуща дейност"], ["s-done", "минала"], ["s-swap", "пропуск / риск"], ["s-piv", "обратна връзка"]],
      build: algos.lifecycle,
      draw(st, f, { frames, i }) {
        st.innerHTML = "";
        const byGen = {};
        frames.slice(0, i + 1).forEach((x) => { (byGen[x.gen] = byGen[x.gen] || {})[x.i] = x.bad ? "s-swap" : "s-done"; });
        const tl = h("div", { class: "timeline" });
        Object.keys(byGen).forEach((g) => {
          const row = h("div", { class: "phase-row" });
          PH.forEach((P, k) => {
            let cls = byGen[g][k] || "s-dim";
            if (+g === f.gen && k === f.i) cls = f.bad ? "s-swap" : f.fb ? "s-piv" : "s-act";
            row.append(h("span", { class: "ph " + cls, title: P.t, text: P.t.split(" ")[0].slice(0, 6) + "." }));
          });
          tl.append(h("div", { class: "tl-row" }, h("span", { text: "версия " + g }), row));
        });
        st.append(tl);
      },
    });
  }

  S.chapter({ id: "zhiznen", order: 5, num: "5", group: "Жизнен цикъл и проектиране", title: "Жизнен цикъл", lead: "От потребност до извеждане от употреба. Обратната връзка от експлоатацията прави процеса цикъл.", html, mount, algos });
})();
